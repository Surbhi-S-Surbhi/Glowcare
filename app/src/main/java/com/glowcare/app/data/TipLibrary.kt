    fun tipsFor(category: Category): List<Tip> = all.filter { it.category == category }

    fun tipById(id: String): Tip? = all.firstOrNull { it.id == id }

    fun search(query: String): List<Tip> {
        val q = query.trim().lowercase()
        if (q.length < 2) return emptyList()
        return all.filter {
            it.title.lowercase().contains(q) ||
                it.short.lowercase().contains(q) ||
                it.detail.lowercase().contains(q) ||
                it.mistake.lowercase().contains(q) ||
                it.category.title.lowercase().contains(q)
        }
    }

    /** Tip for a given day of a journey (no repeats within a program). */
    fun tipForDay(category: Category, day: Int): Tip? {
        val tips = tipsFor(category)
        if (tips.isEmpty()) return null
        return tips[(day - 1) % tips.size]
    }

    /** Localized copy of a tip for the active app language (Hindi via TipLibraryHi). */
    fun localized(tip: Tip): Tip =
        if (LanguagePrefs.current() == "hi") TipLibraryHi.localize(tip) else tip

